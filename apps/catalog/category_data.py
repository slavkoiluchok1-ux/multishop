def product_type_for_path(path: str) -> str | None:
    """Тип товару за коренем гілки категорії (None, якщо гілка невідома)."""
    if not path:
        return None
    allowed = ROOT_PRODUCT_TYPES.get(path.split(" › ", maxsplit=1)[0])
    return allowed[0] if allowed else None


def is_one_time_development_path(path: str) -> bool:
    prefix = "Послуги › Розробка"
    return path == prefix or path.startswith(f"{prefix} › ")


def uses_digital_delivery(product_type: str, category_path: str) -> bool:
    return product_type == "digital_file" or (
        product_type == "service" and is_one_time_development_path(category_path)
    )


