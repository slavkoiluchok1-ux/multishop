# --- Перевірки -----------------------------------------------------------------------

def validate() -> None:
    """Перевіряє дерево й характеристики до запису в БД. Кидає ValueError зі списком проблем."""
    problems = []

    def check(data: TreeNode, path: CategoryPath) -> None:
        """Дублі серед сусідніх вузлів (після norm)."""
        if not data:
            return
        names = [norm(n) for n in data]
        for name in {n for n in names if names.count(n) > 1}:
            problems.append(f"Дубль серед сусідніх вузлів: {' › '.join(path + (name,))}")
        if isinstance(data, dict):
            for name, sub in data.items():
                check(sub, path + (norm(name),))

    check(TREE, ())

    if {norm(n) for n in TREE} != {norm(n) for n in ROOT_PRODUCT_TYPES}:
        problems.append("Кореневі гілки TREE не збігаються з ROOT_PRODUCT_TYPES")

    for root in TREE:
        if not any(
            norm(target[0]) == norm(root)
            for definition in ATTRIBUTES
            for target in definition["targets"]
        ):
            problems.append(f"Гілка без характеристик: {root}")

    for path, is_leaf in walk(TREE):
        if is_leaf and not 2 <= len(path) <= 5:
            problems.append(f"Листок на рівні {len(path)} (дозволено 2–5): {' › '.join(path)}")
        if is_leaf and not any(
            tuple(norm(part) for part in target) == tuple(norm(part) for part in path[:len(target)])
            for definition in ATTRIBUTES
            for target in definition["targets"]
        ):
            problems.append(f"Листок без характеристик: {' › '.join(path)}")

    seen: dict[str, list[CategoryPath]] = {}
    for item in ATTRIBUTES:
        name = item["name"]
        if item["kind"] not in KINDS:
            problems.append(f"{name}: невідомий kind {item['kind']}")
        needs_options = item["kind"] in (KIND_SINGLE, KIND_MULTI)
        if needs_options != bool(item["options"]):
            problems.append(f"{name}: варіанти потрібні лише для вибору одного чи кількох")
        for path in item["targets"]:
            if node_info(path) is None:
                problems.append(f"{name}: вузла немає — {' › '.join(path)}")
                continue
            norm_path = tuple(norm(p) for p in path)
            for other in seen.get(name, []):
                if norm_path[:len(other)] == other or other[:len(norm_path)] == norm_path:
                    problems.append(f"{name}: дублюється на вузлі й предку/нащадку — {' › '.join(path)}")
            seen.setdefault(name, []).append(norm_path)

    if problems:
        raise ValueError("\n".join(problems))


def validate_product(path: Sequence[str], kind: str) -> str | None:
    """Текст проблеми для тестового товару або None, якщо все гаразд."""
    if not path:
        return "шлях категорії порожній"
    leaf = node_info(path)
    if leaf is None:
        return f"шляху немає в дереві: {' › '.join(path)}"
    if not leaf:
        return f"це не листок: {' › '.join(path)}"
    allowed = ROOT_PRODUCT_TYPES.get(norm(path[0]))
    if allowed is None:
        return f"коренева гілка невідома: {path[0]}"
    if kind not in allowed:
        return f"вид {kind} не підходить гілці «{path[0]}» (дозволено: {', '.join(allowed)})"
    return None
