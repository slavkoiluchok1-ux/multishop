"""Дерево каталогу MultiShop: вузли, дозволені види товарів і характеристики.

Використовується командою seed_demo та API каталогу.

Формат дерева:
  dict   — вузол із нащадками {назва: піддерево};
  list   — скорочення для кількох листків ["а", "б"];
  None   — листок (товар лежить лише в листку).
Назви з малої кирилиці автоматично отримують велику першу літеру (norm), назви на кшталт
iPhone чи macOS-утиліти лишаються як є.
Правила розбору DATA_PLAN: перелік через кому в рядку без двокрапки — окремі сусідні вузли;
перелік у дужках після назви, якщо це підтипи (електроінструмент, стилізовані, пресети),
— нащадки; скорочення (UI) лишається в назві.
"""
from collections.abc import Iterator, Sequence
from typing import Literal, TypeAlias, TypedDict

TreeNode: TypeAlias = dict[str, "TreeNode"] | list[str] | None
CategoryPath: TypeAlias = tuple[str, ...]
AttributeKind: TypeAlias = Literal["single", "multiple", "number", "bool"]


class AttributeDefinition(TypedDict):
    name: str
    kind: AttributeKind
    targets: list[CategoryPath]
    unit: str
    required: bool
    options: list[str]


# --- Допоміжне ---------------------------------------------------------------


def L(*names: str) -> dict[str, None]:
    """Кілька листків у dict, коли поруч є вузли з нащадками."""
    return dict.fromkeys(names)


def norm(name: str) -> str:
    """Перша літера велика, крім назв із великою літерою в першому слові (iPhone, macOS-утиліти)."""
    first_word = name.split(" ")[0]
    if name[:1].islower() and not any(c.isupper() for c in first_word):
        return name[:1].upper() + name[1:]
    return name


def children(data: TreeNode) -> dict[str, TreeNode]:
    """Нащадки вузла як {назва: піддерево}. Для листка (None, [], {}) порожній словник."""
    if not data:
        return {}
    if isinstance(data, list):
        return {norm(n): None for n in data}
    return {norm(n): sub for n, sub in data.items()}


def walk(
    data: TreeNode, path: CategoryPath = ()
) -> Iterator[tuple[CategoryPath, bool]]:
    """Усі вузли дерева: (шлях, чи_листок)."""
    for name, sub in children(data).items():
        node_path = path + (name,)
        yield node_path, not children(sub)
        yield from walk(sub, node_path)


def node_info(path: Sequence[str]) -> bool | None:
    """None, якщо шляху немає; True для листка; False для вузла з нащадками."""
    data = TREE
    for name in path:
        kids = children(data)
        key = norm(name)
        if key not in kids:
            return None
        data = kids[key]
    return not children(data)


